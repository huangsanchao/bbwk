/**
 * 按分类随机获取题目
 * @param {string} category - 分类名称（备孕/孕期/喂养/健康/心理）
 * @param {number} count - 获取题目数量，默认10
 * @returns {Array} 随机抽取的题目数组
 */
export function getQuestionsByCategory(category, count = 10) {
  const filtered = questionBank.filter(q => q.category === category);
  return shuffleArray(filtered).slice(0, count);
}

/**
 * 随机获取题目（跨分类）
 * @param {number} count - 获取题目数量，默认20
 * @returns {Array} 随机抽取的题目数组
 */
export function getRandomQuestions(count = 20) {
  return shuffleArray([...questionBank]).slice(0, count);
}

